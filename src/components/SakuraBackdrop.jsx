import { useEffect, useState } from 'react';
import tree from '../assets/sakura-tree.svg?raw'; // generated by .impeccable/mocks/sakura/tree.mjs (seed 7)

// left %, cycle seconds, start offset, resting height for reduced motion
const PETALS = [
  [24, 19, -3, '22svh'],
  [54, 23, -11, '41svh'],
  [12, 21, -16, '58svh'],
  [77, 26, -7, '33svh'],
  [40, 24, -20, '70svh'],
];

// Behind everything and never tappable; the petals stop while the app is in the background.
export default function SakuraBackdrop({ quiet }) {
  const [hidden, setHidden] = useState(document.hidden);
  useEffect(() => {
    const onVis = () => setHidden(document.hidden);
    document.addEventListener('visibilitychange', onVis);
    return () => document.removeEventListener('visibilitychange', onVis);
  }, []);

  return (
    <div
      className="sakura absolute inset-0 -z-10 overflow-hidden pointer-events-none"
      data-quiet={quiet || undefined}
      data-paused={hidden || undefined}
      aria-hidden="true"
    >
      <div className="mt-8" dangerouslySetInnerHTML={{ __html: tree }} />
      {PETALS.map(([left, dur, delay, rest]) => (
        <i
          key={left}
          className="petal"
          style={{ left: `${left}%`, animationDuration: `${dur}s`, animationDelay: `${delay}s`, '--rest': rest }}
        />
      ))}
    </div>
  );
}
